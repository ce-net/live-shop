//! A replicated log for the cells where last-writer-wins is wrong (stock, order sagas).
//!
//! One leader per epoch, elected by a majority vote in which a replica only votes for a candidate whose log is at
//! least as complete as its own. The leader answers a proposal only after a majority has the entry, and a replica
//! refuses every `Append` whose epoch is below the highest it has seen, so a deposed leader that has not noticed
//! cannot commit anything (fencing by epoch, not by clocks). The state machine applies committed entries in order
//! on every replica.
//!
//! This is the stand-in for `ce-replica`'s lease plus `consensus.log@1`; the peer contract is the cell's own
//! (`<cell>.peer`), generated by [`peer_api!`].
use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};
use shop_wire::chain::Holder;
use shop_wire::ts::{Registry, Ts};
use shop_wire::{Client, Op, Server};
use std::collections::HashMap;
use std::fs::{File, OpenOptions};
use std::future::Future;
use std::io::{BufRead, BufReader, Write};
use std::marker::PhantomData;
use std::path::PathBuf;
use std::pin::Pin;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};
use tokio::sync::{oneshot, Notify};

// ------------------------------------------------------------------------------------------- peer types

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LogEntry<E> {
    pub term: u64,
    pub idx: u64,
    /// `None` is the no-op a new leader appends to commit everything before it.
    pub entry: Option<E>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VoteReq {
    pub term: u64,
    pub candidate: u32,
    pub last_idx: u64,
    pub last_term: u64,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VoteResp {
    pub term: u64,
    pub granted: bool,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AppendReq<E> {
    pub term: u64,
    pub leader: u32,
    pub prev_idx: u64,
    pub prev_term: u64,
    pub entries: Vec<LogEntry<E>>,
    pub commit: u64,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AppendResp {
    pub term: u64,
    pub ok: bool,
    pub last: u64,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TailReq {
    pub from: u64,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TailResp<E> {
    pub term: u64,
    pub commit: u64,
    pub entries: Vec<LogEntry<E>>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum PeerError {
    Stopped,
}

macro_rules! ts_struct {
    ($t:ident $(<$g:ident>)? { $($f:ident: $ft:ty),* }) => {
        impl$(<$g: Ts>)? Ts for $t$(<$g>)? {
            fn ts_ref(reg: &mut Registry) -> String {
                #[allow(unused_mut)]
                let mut n = stringify!($t).to_string();
                $( n = format!("{}{}", n, <$g as Ts>::ts_ref(reg)); )?
                if reg.begin(&n, concat!(module_path!(), "::", stringify!($t))) {
                    let mut s = format!("export interface {n} {{\n");
                    $( { let t = <$ft as Ts>::ts_ref(reg); s.push_str(&format!("  {}: {};\n", stringify!($f), t)); } )*
                    s.push_str("}\n");
                    reg.finish(&n, s);
                }
                n
            }
        }
    };
}
ts_struct!(LogEntry<E> { term: u64, idx: u64, entry: Option<E> });
ts_struct!(VoteReq { term: u64, candidate: u32, last_idx: u64, last_term: u64 });
ts_struct!(VoteResp { term: u64, granted: bool });
ts_struct!(AppendReq<E> { term: u64, leader: u32, prev_idx: u64, prev_term: u64, entries: Vec<LogEntry<E>>, commit: u64 });
ts_struct!(AppendResp { term: u64, ok: bool, last: u64 });
ts_struct!(TailReq { from: u64 });
ts_struct!(TailResp<E> { term: u64, commit: u64, entries: Vec<LogEntry<E>> });
impl Ts for PeerError {
    fn ts_ref(reg: &mut Registry) -> String {
        if reg.begin("PeerError", "shop_replog::PeerError") {
            reg.finish("PeerError", "export type PeerError = \"Stopped\";\n".into());
        }
        "PeerError".into()
    }
}

/// The peer contract of a replicated cell: `Vote`, `Append` and `Tail` over the cell's own entry type.
#[macro_export]
macro_rules! peer_api {
    ($api:ident = $name:literal, entry $e:ty, needs $right:literal) => {
        shop_wire::api! {
            api $api = $name, version 1;
            types {}
            ops {
                2 => Vote($crate::VoteReq) -> $crate::VoteResp | $crate::PeerError, needs $right, deadline_ms 600;
                3 => Append($crate::AppendReq<$e>) -> $crate::AppendResp | $crate::PeerError, needs $right, deadline_ms 1500;
                4 => Tail($crate::TailReq) -> $crate::TailResp<$e> | $crate::PeerError, needs $right, deadline_ms 5000;
            }
        }
    };
}

// ------------------------------------------------------------------------------------------- machine

/// The deterministic state machine every replica runs over the committed log.
pub trait Machine: Default + Send + 'static {
    type Entry: Clone + Serialize + DeserializeOwned + Send + Sync + 'static;
    type Out: Clone + Send + 'static;
    fn apply(&mut self, idx: u64, e: &Self::Entry) -> Self::Out;
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProposeError {
    NotLeader(Option<usize>),
    /// No majority answered in time. The entry may still commit later; callers retry idempotently.
    NoQuorum,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum Role {
    Follower,
    Candidate,
    Leader,
}

pub struct Config {
    pub me: usize,
    pub peers: Vec<String>,
    pub dir: PathBuf,
    /// Test flag: the leader answers after its own write only and replicates every 3 s. It exists to show
    /// that the chaos proof's A1 can fail; never set it otherwise.
    pub unsafe_local_ack: bool,
}

type Waiter<O> = (u64, oneshot::Sender<Result<O, ProposeError>>);

struct State<M: Machine> {
    term: u64,
    voted: Option<u32>,
    log: Vec<LogEntry<M::Entry>>,
    commit: u64,
    applied: u64,
    role: Role,
    leader: Option<usize>,
    deadline: Instant,
    m: M,
    waiters: HashMap<u64, Vec<Waiter<M::Out>>>,
    next: Vec<u64>,
    matched: Vec<u64>,
    file: File,
    meta: PathBuf,
}

impl<M: Machine> State<M> {
    fn last(&self) -> (u64, u64) {
        self.log.last().map(|e| (e.idx, e.term)).unwrap_or((0, 0))
    }
    fn term_at(&self, idx: u64) -> Option<u64> {
        if idx == 0 {
            return Some(0);
        }
        self.log.get(idx as usize - 1).map(|e| e.term)
    }
    fn save_meta(&self) {
        let tmp = self.meta.with_extension("tmp");
        let _ = std::fs::write(&tmp, serde_json::json!({ "term": self.term, "voted": self.voted }).to_string());
        let _ = std::fs::rename(&tmp, &self.meta);
    }
    fn write(&mut self, e: &LogEntry<M::Entry>) {
        let mut line = serde_json::to_vec(e).expect("entry encodes");
        line.push(b'\n');
        self.file.write_all(&line).expect("log write");
    }
    fn step_down(&mut self, term: u64) {
        if term > self.term {
            self.term = term;
            self.voted = None;
            self.save_meta();
        }
        if self.role == Role::Leader {
            // proposals still waiting may or may not commit under the next leader; their callers retry
            for (_, ws) in self.waiters.drain() {
                for (_, w) in ws {
                    let _ = w.send(Err(ProposeError::NotLeader(None)));
                }
            }
        }
        self.role = Role::Follower;
    }
    fn apply_to(&mut self, commit: u64) {
        while self.applied < commit.min(self.log.len() as u64) {
            self.applied += 1;
            let e = self.log[self.applied as usize - 1].clone();
            let out = e.entry.as_ref().map(|x| self.m.apply(e.idx, x));
            if let Some(ws) = self.waiters.remove(&e.idx) {
                for (term, w) in ws {
                    let r = match (&out, term == e.term) {
                        (Some(o), true) => Ok(o.clone()),
                        _ => Err(ProposeError::NotLeader(self.leader)),
                    };
                    let _ = w.send(r);
                }
            }
        }
    }
    /// Keep the log up to `idx` (exclusive of what follows). Only the unsafe test mode can cut below `applied`;
    /// then the machine is rebuilt from the kept log.
    fn truncate(&mut self, keep: u64) {
        self.log.truncate(keep as usize);
        if self.applied > keep {
            self.m = M::default();
            self.applied = 0;
            self.commit = self.commit.min(keep);
            self.apply_to(self.commit);
        }
    }
}

fn rand_ms(lo: u64, hi: u64) -> Duration {
    let mut b = [0u8; 8];
    getrandom::getrandom(&mut b).unwrap();
    Duration::from_millis(lo + u64::from_le_bytes(b) % (hi - lo))
}

type BoxFut<T> = Pin<Box<dyn Future<Output = Option<T>> + Send>>;

/// How a replica reaches its peers. [`WirePeers`] is the typed implementation over the cell's peer contract.
pub trait Peers<E>: Send + Sync + 'static {
    fn vote(&self, peer: usize, req: VoteReq) -> BoxFut<VoteResp>;
    fn append(&self, peer: usize, req: AppendReq<E>) -> BoxFut<AppendResp>;
}

pub struct WirePeers<V, A> {
    addrs: Vec<String>,
    holder: Arc<Holder>,
    _p: PhantomData<fn() -> (V, A)>,
}

impl<V, A> WirePeers<V, A> {
    pub fn new(addrs: Vec<String>, holder: Arc<Holder>) -> Self {
        WirePeers { addrs, holder, _p: PhantomData }
    }
}

impl<E, V, A> Peers<E> for WirePeers<V, A>
where
    E: Clone + Serialize + DeserializeOwned + Send + Sync + 'static,
    V: Op<Req = VoteReq, Ok = VoteResp, Err = PeerError>,
    A: Op<Req = AppendReq<E>, Ok = AppendResp, Err = PeerError>,
{
    fn vote(&self, peer: usize, req: VoteReq) -> BoxFut<VoteResp> {
        let c = Client::with(self.addrs[peer].clone(), Some(self.holder.clone()));
        Box::pin(async move { c.call::<V>(&req).await.ok().and_then(|r| r.ok()) })
    }
    fn append(&self, peer: usize, req: AppendReq<E>) -> BoxFut<AppendResp> {
        let c = Client::with(self.addrs[peer].clone(), Some(self.holder.clone()));
        Box::pin(async move { c.call::<A>(&req).await.ok().and_then(|r| r.ok()) })
    }
}

/// One replica of a replicated log.
pub struct Log<M: Machine> {
    st: Arc<Mutex<State<M>>>,
    peers: Arc<dyn Peers<M::Entry>>,
    wake: Arc<Notify>,
    me: usize,
    n: usize,
    unsafe_local_ack: bool,
}

impl<M: Machine> Clone for Log<M> {
    fn clone(&self) -> Self {
        Log { st: self.st.clone(), peers: self.peers.clone(), wake: self.wake.clone(), me: self.me, n: self.n, unsafe_local_ack: self.unsafe_local_ack }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct Status {
    pub role: Role,
    pub term: u64,
    pub commit: u64,
    pub last: u64,
    pub leader: Option<usize>,
}

impl<M: Machine> Log<M> {
    /// Open (or create) the replica's log in `cfg.dir` and start its election and replication loops.
    pub fn open(cfg: Config, peers: Arc<dyn Peers<M::Entry>>) -> Log<M> {
        std::fs::create_dir_all(&cfg.dir).expect("log dir");
        let meta = cfg.dir.join("meta.json");
        let (term, voted) = std::fs::read(&meta)
            .ok()
            .and_then(|b| serde_json::from_slice::<serde_json::Value>(&b).ok())
            .map(|v| (v["term"].as_u64().unwrap_or(0), v["voted"].as_u64().map(|x| x as u32)))
            .unwrap_or((0, None));
        let path = cfg.dir.join("log.jsonl");
        let mut log: Vec<LogEntry<M::Entry>> = Vec::new();
        if let Ok(f) = File::open(&path) {
            for line in BufReader::new(f).lines().map_while(Result::ok) {
                // a torn last line from a kill is skipped
                if let Ok(e) = serde_json::from_str::<LogEntry<M::Entry>>(&line) {
                    log.truncate(e.idx as usize - 1);
                    log.push(e);
                }
            }
        }
        let file = OpenOptions::new().create(true).append(true).open(&path).expect("log file");
        let n = cfg.peers.len();
        let slow = if cfg.unsafe_local_ack { 12 } else { 1 };
        let st = State {
            term,
            voted,
            log,
            commit: 0,
            applied: 0,
            role: Role::Follower,
            leader: None,
            deadline: Instant::now() + rand_ms(500 * slow, 1000 * slow),
            m: M::default(),
            waiters: HashMap::new(),
            next: vec![1; n],
            matched: vec![0; n],
            file,
            meta,
        };
        let l = Log { st: Arc::new(Mutex::new(st)), peers, wake: Arc::new(Notify::new()), me: cfg.me, n, unsafe_local_ack: cfg.unsafe_local_ack };
        l.spawn_loops();
        l
    }

    fn majority(&self) -> usize {
        self.n / 2 + 1
    }

    pub fn status(&self) -> Status {
        let s = self.st.lock().unwrap();
        Status { role: s.role, term: s.term, commit: s.commit, last: s.last().0, leader: s.leader }
    }

    /// True on a leader whose own epoch's no-op has committed and been applied: its state then includes every
    /// entry any earlier leader acknowledged, so a read here is current.
    pub fn ready(&self) -> bool {
        let s = self.st.lock().unwrap();
        s.role == Role::Leader && s.term_at(s.commit) == Some(s.term) && s.applied >= s.commit
    }

    /// Read the applied state of this replica (any role).
    pub fn read<R>(&self, f: impl FnOnce(&M, u64) -> R) -> R {
        let s = self.st.lock().unwrap();
        f(&s.m, s.applied)
    }

    /// Append `e` and answer with its result once a majority has it and it is applied here.
    pub async fn propose(&self, e: M::Entry) -> Result<M::Out, ProposeError> {
        let rx = {
            let mut s = self.st.lock().unwrap();
            if s.role != Role::Leader {
                return Err(ProposeError::NotLeader(s.leader));
            }
            let idx = s.last().0 + 1;
            let le = LogEntry { term: s.term, idx, entry: Some(e) };
            s.write(&le);
            s.log.push(le);
            let (tx, rx) = oneshot::channel();
            let t = s.term;
            s.waiters.entry(idx).or_default().push((t, tx));
            if self.unsafe_local_ack {
                s.commit = idx;
                s.apply_to(idx);
            } else if self.n == 1 {
                s.commit = idx;
                s.apply_to(idx);
            }
            rx
        };
        self.wake.notify_waiters();
        match tokio::time::timeout(Duration::from_secs(4), rx).await {
            Ok(Ok(r)) => r,
            _ => Err(ProposeError::NoQuorum),
        }
    }

    pub fn handle_vote(&self, r: VoteReq) -> VoteResp {
        let mut s = self.st.lock().unwrap();
        if r.term < s.term {
            return VoteResp { term: s.term, granted: false };
        }
        if r.term > s.term {
            s.step_down(r.term);
        }
        let (li, lt) = s.last();
        let up_to_date = r.last_term > lt || (r.last_term == lt && r.last_idx >= li);
        let granted = up_to_date && s.voted.is_none_or(|v| v == r.candidate);
        if granted {
            s.voted = Some(r.candidate);
            s.save_meta();
            let slow = if self.unsafe_local_ack { 12 } else { 1 };
            s.deadline = Instant::now() + rand_ms(500 * slow, 1000 * slow);
        }
        VoteResp { term: s.term, granted }
    }

    pub fn handle_append(&self, r: AppendReq<M::Entry>) -> AppendResp {
        let mut s = self.st.lock().unwrap();
        if r.term < s.term {
            // fencing: a deposed leader's writes are refused here
            return AppendResp { term: s.term, ok: false, last: s.last().0 };
        }
        if r.term > s.term || s.role != Role::Follower {
            s.step_down(r.term);
        }
        s.leader = Some(r.leader as usize);
        let slow = if self.unsafe_local_ack { 12 } else { 1 };
        s.deadline = Instant::now() + rand_ms(500 * slow, 1000 * slow);
        if s.term_at(r.prev_idx) != Some(r.prev_term) {
            let last = s.last().0.min(r.prev_idx.saturating_sub(1));
            return AppendResp { term: s.term, ok: false, last };
        }
        for e in r.entries.iter() {
            match s.term_at(e.idx) {
                Some(t) if t == e.term => continue,
                Some(_) => {
                    s.truncate(e.idx - 1);
                }
                None => {}
            }
            s.write(e);
            s.log.push(e.clone());
        }
        let upto = r.prev_idx + r.entries.len() as u64;
        let c = r.commit.min(upto).max(s.commit.min(s.log.len() as u64));
        if c > s.commit {
            s.commit = c;
        }
        let c = s.commit;
        s.apply_to(c);
        AppendResp { term: s.term, ok: true, last: upto }
    }

    pub fn handle_tail(&self, r: TailReq) -> TailResp<M::Entry> {
        let s = self.st.lock().unwrap();
        let from = r.from.max(1) as usize - 1;
        TailResp { term: s.term, commit: s.commit, entries: s.log.get(from..).map(|x| x.to_vec()).unwrap_or_default() }
    }

    /// Register this replica's `Vote`, `Append`, `Tail` handlers on the cell's peer server.
    pub fn serve<V, A, T>(&self, server: Server) -> Server
    where
        V: Op<Req = VoteReq, Ok = VoteResp, Err = PeerError>,
        A: Op<Req = AppendReq<M::Entry>, Ok = AppendResp, Err = PeerError>,
        T: Op<Req = TailReq, Ok = TailResp<M::Entry>, Err = PeerError>,
    {
        let (a, b, c) = (self.clone(), self.clone(), self.clone());
        server
            .on::<V, _, _>(move |_, r| {
                let a = a.clone();
                async move { Ok(a.handle_vote(r)) }
            })
            .on::<A, _, _>(move |_, r| {
                let b = b.clone();
                async move { Ok(b.handle_append(r)) }
            })
            .on::<T, _, _>(move |_, r| {
                let c = c.clone();
                async move { Ok(c.handle_tail(r)) }
            })
    }

    fn spawn_loops(&self) {
        // election timer
        let l = self.clone();
        tokio::spawn(async move {
            loop {
                tokio::time::sleep(Duration::from_millis(40)).await;
                let due = {
                    let s = l.st.lock().unwrap();
                    s.role != Role::Leader && Instant::now() >= s.deadline
                };
                if due {
                    l.elect().await;
                }
            }
        });
        // one replication loop per peer
        for p in 0..self.n {
            if p == self.me {
                continue;
            }
            let l = self.clone();
            tokio::spawn(async move {
                let beat = Duration::from_millis(if l.unsafe_local_ack { 3000 } else { 50 });
                loop {
                    if l.unsafe_local_ack {
                        tokio::time::sleep(beat).await;
                    } else {
                        let _ = tokio::time::timeout(beat, l.wake.notified()).await;
                    }
                    l.replicate(p).await;
                }
            });
        }
    }

    async fn elect(&self) {
        let (req, term) = {
            let mut s = self.st.lock().unwrap();
            s.term += 1;
            s.role = Role::Candidate;
            s.voted = Some(self.me as u32);
            s.leader = None;
            s.save_meta();
            let slow = if self.unsafe_local_ack { 12 } else { 1 };
            s.deadline = Instant::now() + rand_ms(500 * slow, 1000 * slow);
            let (li, lt) = s.last();
            (VoteReq { term: s.term, candidate: self.me as u32, last_idx: li, last_term: lt }, s.term)
        };
        let mut votes = 1;
        let mut futs = Vec::new();
        for p in 0..self.n {
            if p != self.me {
                futs.push(self.peers.vote(p, req.clone()));
            }
        }
        for f in futs {
            if let Some(r) = f.await {
                let mut s = self.st.lock().unwrap();
                if r.term > s.term {
                    s.step_down(r.term);
                    return;
                }
                if r.granted {
                    votes += 1;
                }
            }
        }
        let mut s = self.st.lock().unwrap();
        if s.role == Role::Candidate && s.term == term && votes >= self.majority() {
            s.role = Role::Leader;
            s.leader = Some(self.me);
            let last = s.last().0;
            s.next = vec![last + 1; self.n];
            s.matched = vec![0; self.n];
            s.matched[self.me] = last;
            // the no-op of this epoch: once it commits, everything before it is committed too
            let le = LogEntry { term, idx: last + 1, entry: None };
            s.write(&le);
            s.log.push(le);
            s.matched[self.me] = last + 1;
            drop(s);
            self.wake.notify_waiters();
        }
    }

    async fn replicate(&self, p: usize) {
        let req = {
            let s = self.st.lock().unwrap();
            if s.role != Role::Leader {
                return;
            }
            let next = s.next[p].max(1);
            let prev_idx = next - 1;
            let Some(prev_term) = s.term_at(prev_idx) else { return };
            let entries: Vec<_> = s.log.get(prev_idx as usize..).map(|x| x.iter().take(512).cloned().collect()).unwrap_or_default();
            AppendReq { term: s.term, leader: self.me as u32, prev_idx, prev_term, entries, commit: s.commit }
        };
        let sent_term = req.term;
        let n_sent = req.entries.len() as u64;
        let prev = req.prev_idx;
        let Some(r) = self.peers.append(p, req).await else { return };
        let mut s = self.st.lock().unwrap();
        if r.term > s.term {
            s.step_down(r.term);
            return;
        }
        if s.role != Role::Leader || s.term != sent_term {
            return;
        }
        if r.ok {
            s.matched[p] = s.matched[p].max(prev + n_sent);
            s.next[p] = s.matched[p] + 1;
            let me = self.me;
            s.matched[me] = s.last().0;
            let mut m = s.matched.clone();
            m.sort_unstable_by(|a, b| b.cmp(a));
            let n = m[self.majority() - 1];
            if n > s.commit && s.term_at(n) == Some(s.term) {
                s.commit = n;
                s.apply_to(n);
            }
            let more = s.next[p] <= s.last().0;
            drop(s);
            if more {
                self.wake.notify_waiters();
            }
        } else {
            s.next[p] = (r.last + 1).min(prev).max(1);
        }
    }
}
